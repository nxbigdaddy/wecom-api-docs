def sanitize_filename(name):
    name = re.sub(r'[\\/:*?"<>|]', '_', name)
    name = re.sub(r'\s+', '_', name)
    return name[:100]

async def fetch_api(session, api_dir, path_id, name, semaphore):
    async with semaphore:
        url = f"{BASE_URL}{path_id}"
        for attempt in range(3):
            try:
                async with session.get(url, timeout=aiohttp.ClientTimeout(total=30)) as resp:
                    if resp.status == 429:
                        wait = 3 * (attempt + 1)
                        print(f"[429] {name}: 等待{wait}s后重试")
                        await asyncio.sleep(wait)
                        continue
                    if resp.status != 200:
                        print(f"[ERR] {name}: HTTP {resp.status}")
                        return False
                    html = await resp.text()
                
                title_m = re.search(r'<title[^>]*>([^<]+)</title>', html, re.I)
                title = title_m.group(1).split(' - ')[0].strip() if title_m else name
                
                content_m = re.search(r'<article[^>]*>([\s\S]*?)</article>', html, re.I)
                if content_m:
                    content = content_m.group(1)
                    content = re.sub(r'<script[\s\S]*?</script>', '', content, flags=re.I)
                    content = re.sub(r'<style[\s\S]*?</style>', '', content, flags=re.I)
                    content = re.sub(r'<!--[\s\S]*?-->', '', content)
                    content = re.sub(r'<[^>]+>', ' ', content)
                    content = re.sub(r'\s+', ' ', content).strip()
                else:
                    content = "内容提取失败"
                
                md = f"# {title}\n\n> 来源: [{url}]({url})\n\n{content}"
                
                out_dir = OUTPUT_DIR / api_dir
                out_dir.mkdir(parents=True, exist_ok=True)
                fname = f"{sanitize_filename(name)}.md"
                (out_dir / fname).write_text(md, encoding='utf-8')
                print(f"[OK] {api_dir}/{fname}")
                return True
            except Exception as e:
                if attempt < 2:
                    await asyncio.sleep(3 * (attempt + 1))
                else:
                    print(f"[ERR] {name}: {str(e)[:60]}")
                    return False
        return False

async def main():
    print(f"开始抓取 {len(APIS)} 个API接口...")
    OUTPUT_DIR.mkdir(parents=True, exist_ok=True)
    semaphore = asyncio.Semaphore(CONCURRENCY)
    
    async with aiohttp.ClientSession() as session:
        tasks = []
        ok = 0
        for api_dir, path_id, name in APIS:
            tasks.append(fetch_api(session, api_dir, path_id, name, semaphore))
            if len(tasks) >= CONCURRENCY:
                results = await asyncio.gather(*tasks)
                ok += sum(1 for r in results if r)
                tasks = []
                await asyncio.sleep(DELAY)
        if tasks:
            results = await asyncio.gather(*tasks)
            ok += sum(1 for r in results if r)
    
    print(f"\n=== 抓取完成! 成功: {ok}/{len(APIS)} ===")

if __name__ == "__main__":
    asyncio.run(main())
